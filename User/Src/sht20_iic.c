#include "sht20_iic.h"

/*
PB8---SCL--开漏
PB9---SDA--开漏
*/
void IIC_GPIO_Init(void)
{
	RCC->AHB1ENR |=(1<<1);
	
	GPIOB->MODER &=(~(15<<16));
	GPIOB->MODER |=(5<<16);
	
	GPIOB->OTYPER |=(3<<8);//开漏输出
	
	GPIOB->OSPEEDR &=(~(15<<16));
	GPIOB->OSPEEDR |=(10<<16);//50mhz
	

	// 总线空闲：SCL=1 SDA=1（开漏写1，释放总线）
    SCL_H();
    SDA_H();
}

/*******************************************************************
函数功能 ：起始信号
*******************************************************************/
void IIC_Start(void)
{
	SDA_H();
	SCL_H();
	TIM3_us(5);
	SDA_L();
	TIM3_us(4);
	SCL_L();
}

/*******************************************************************
函数功能：结束信号
*******************************************************************/
void IIC_Stop(void)
{
    SCL_L();
    SDA_L();
	TIM3_us(5);
    SCL_H();
	TIM3_us(5);
    SDA_H();
}

/**********************************************************************
函数功能：发送应答（主机发送ACK给从机）
**********************************************************************/
void IIC_Send_ACK(void)
{
	SCL_L();
	SDA_L();
	TIM3_us(5);
	SCL_H();
	TIM3_us(4);
	SCL_L();
}

/*******************************************************************
函数功能 ：发送非应答信号
*******************************************************************/
void IIC_Send_NoACK(void)
{
	SCL_L();
	SDA_H();
	TIM3_us(4);
	SCL_H();
	TIM3_us(4);
	SCL_L();
}

/*******************************************************************
函数功能 ：发送8位数据
函数参数：dat：要发送的数据
*******************************************************************/
void IIC_Send_Data(u8 dat)
{
	u8 i;
	SCL_L();
	for(i = 0; i < 8; i++)
	{
		if(dat & 0x80)
		{
			SDA_H();
		}
		else
		{
			SDA_L();
		}
		dat <<= 1;
		TIM3_us(5);
		SCL_H();
		TIM3_us(4);
		SCL_L();	
	}
}

/*******************************************************************
函数功能 ：等待应答---等待从机发送过来的应答和非应答
函数返回值：0：应答；1：非应答
*******************************************************************/
u8 IIC_Get_ACK(void)
{
    u8 ack = 0;
    
    SCL_L();
    SDA_H();        // 开漏写1，释放SDA，交给从机驱动
    TIM3_us(5);
    
    SCL_H();
    TIM3_us(5);
    
    if(READ_SDA())
    {
        ack = 1;
    }
    else
    {
        ack = 0;
    }
    
    SCL_L();
    return ack;
}

/*******************************************************************
函数功能 ：读取8位数据
函数参数：ack：1发送ACK，0发送NACK
函数返回值：读取到的数据
*******************************************************************/
u8 IIC_Read_Data(u8 ack)
{
	u8 i,date = 0;
	SDA_H(); //释放SDA，从机输出数据
	
	for(i = 0; i < 8; i++)
	{	
		SCL_L();
		TIM3_us(5);
		SCL_H();
		date <<= 1;
		if( READ_SDA() )
		{
			date++;
		}
		TIM3_us(4);
	}
	if(ack)
	{
		IIC_Send_ACK();
	}
	else
	{
		IIC_Send_NoACK();
	}
	return date;
}



